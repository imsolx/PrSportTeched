    await page.locator('#admin-users-refresh').click();
    await expect(page.locator('#admin-users-loading')).toBeVisible();
    await expect(page.locator('#admin-users-error')).toContainText('ทดสอบโหลดข้อมูลไม่สำเร็จ');
