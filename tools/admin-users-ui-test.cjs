    await page.unroute('**/api.php?action=users.save');
    let memberSaves = 0;
    page.on('request', request => { if (request.url().includes('action=users.save') && request.postDataJSON()?.email === 'member@ui-admin.local') memberSaves++; });
    await page.evaluate(() => { const form = document.querySelector('#user-form'); form.requestSubmit(); form.requestSubmit(); });
    await expect(page.locator('#user-form-dialog')).toBeHidden();
    await expect(page.locator('#users-table tbody')).toContainText('member@ui-admin.local');
    expect(memberSaves).toBe(1);

    const memberRow = () => page.locator('#users-table tbody tr', { hasText: 'member@ui-admin.local' });
    await memberRow().getByRole('button', { name: 'จัดการสมาชิก ทีมงานทดสอบ UI', exact: true }).click();
    await page.locator('[data-admin-member-action="edit"]').click();
    await expect(page.locator('#admin-user-password-fields')).not.toHaveAttribute('open', '');
    await expect(page.locator('#user-form [name=password]')).toHaveValue('');
    await page.locator('#user-form [name=name]').fill('ทีมงานที่แก้ไขแล้ว');
    await page.locator('#user-role-select').selectOption('sport_head');
    await expect(page.locator('#admin-user-scope-fields')).toBeVisible();
    await page.locator('#admin-user-sport-options input').first().check();
    await page.locator('#user-form [name=department_code]').selectOption({ index: 1 });
    await page.locator('#user-form [type=submit]').click();
    await expect(page.locator('.confirm-dialog')).toBeVisible();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'กลับ', exact: true }).click();
    await expect(page.locator('#user-form-dialog')).toBeVisible();
    await page.locator('#user-form [type=submit]').click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'ยืนยันการเปลี่ยนแปลง', exact: true }).click();
    await expect(page.locator('#user-form-dialog')).toBeHidden();
    await expect(memberRow()).toContainText('Sport Manager');
    await page.locator('#admin-member-search').fill('แก้ไขแล้ว');
    await expect(page.locator('#users-table tbody tr')).toHaveCount(1);
    await page.locator('#admin-member-role-filter').selectOption('public_relations');
    await expect(page.locator('#users-table .empty-state')).toContainText('ไม่พบสมาชิก');
    await page.locator('#admin-member-role-filter').selectOption('sport_head');
    await expect(memberRow()).toBeVisible();
    await memberRow().getByRole('button').click();
    await page.locator('[data-admin-member-action="status"]').click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'กลับ', exact: true }).click();
    await expect(memberRow()).toContainText('เปิดใช้งาน');
    await memberRow().getByRole('button').click();
    await page.locator('[data-admin-member-action="status"]').click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'ระงับบัญชี', exact: true }).click();
    await expect(memberRow()).toContainText('ระงับบัญชี');
    await page.locator('#admin-member-status-filter').selectOption('inactive');
    await expect(page.locator('#users-table tbody tr')).toHaveCount(1);
    await page.locator('#admin-member-status-filter').selectOption('active');
    await expect(page.locator('#users-table .empty-state')).toBeVisible();
    await page.locator('#admin-member-status-filter').selectOption('');
    await page.locator('#admin-member-search').fill('');
    await page.locator('#admin-member-role-filter').selectOption('');
    await capture('members-desktop');

    await tab('settings');
    await expect(page.locator('#staff-invite-expiry')).toHaveValue('45');
    await page.locator('#staff-invite-expiry').fill('90');
    await page.locator('#admin-invite-settings-form [type=submit]').click();
    await expect(page.locator('#admin-settings-feedback')).toHaveText('บันทึกการตั้งค่าแล้ว');
    await page.reload();
    await expect(page.locator('#users-table tbody')).toContainText('admin@rmutt.local');
    await tab('settings');
    await expect(page.locator('#staff-invite-expiry')).toHaveValue('90');
    await page.locator('#staff-invites-enabled').uncheck();
    await page.locator('#admin-invite-settings-form [type=submit]').click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'ปิดใช้คำเชิญ', exact: true }).click();
    await expect(page.locator('#admin-settings-feedback')).toHaveText('บันทึกการตั้งค่าแล้ว');
    await tab('invitations');
    await expect(page.locator('#admin-create-invite')).toBeDisabled();
    await expect(page.locator('#admin-invite-notice')).toContainText('ปิดใช้');
    await tab('settings');
    await page.locator('#staff-invites-enabled').check();
    await page.locator('#admin-invite-settings-form [type=submit]').click();
    await expect(page.locator('#admin-settings-feedback')).toHaveText('บันทึกการตั้งค่าแล้ว');
    await capture('settings-desktop');

    await tab('invitations');
    await page.locator('#admin-create-invite').click();
    await expect(page.locator('#invite-form input[type=password]')).toHaveCount(0);
    await page.locator('#invite-form [name=email]').fill('invite@ui-admin.local');
    await page.locator('#invite-form [name=name]').fill('ผู้รับเชิญทดสอบ');
    await page.locator('#invite-role-select').selectOption('result_officer');
    await expect(page.locator('#admin-invite-lifetime')).toContainText('90 นาที');
    await page.locator('#invite-form [type=submit]').click();
    await expect(page.locator('#invite-form-dialog')).toBeHidden();
    const inviteRow = () => page.locator('#invites-table tbody tr', { hasText: 'invite@ui-admin.local' }).filter({ hasText: 'รอตอบรับ' });
    await expect(inviteRow()).toContainText('Match Official');
    const oldLink = await page.locator('#invite-link-box input').inputValue();
    await page.locator('#invite-link-box').getByRole('button', { name: 'คัดลอกลิงก์', exact: true }).click();
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(oldLink);
    await page.reload();
    await expect(page.locator('#users-table tbody')).toContainText('admin@rmutt.local');
    await tab('invitations');
    await inviteRow().getByRole('button', { name: 'คัดลอกลิงก์', exact: true }).click();
    await expect(page.locator('.confirm-dialog')).toContainText('ลิงก์เดิมจะใช้ไม่ได้');
    await page.locator('.confirm-dialog').getByRole('button', { name: 'สร้างคำเชิญใหม่', exact: true }).click();
    await expect(page.locator('#invite-link-box input')).not.toHaveValue(oldLink);
    const freshLink = await page.locator('#invite-link-box input').inputValue();
    const pendingId = await page.evaluate(() => app.invites.find(row => row.email === 'invite@ui-admin.local' && row.status === 'pending').id);
    const expired = spawnSync(php, ['-r', '$pdo = new PDO(getenv("PRSPORT_DB_DSN")); $stmt = $pdo->prepare("UPDATE user_invites SET expires_at = ? WHERE id = ?"); $stmt->execute(["2000-01-01 00:00:00", $argv[1]]);', String(pendingId)], { env: { ...process.env, PRSPORT_DB_DSN: 'sqlite:' + db }, windowsHide: true });
    if (expired.status !== 0) throw new Error(expired.stderr.toString());
    await page.locator('#admin-users-refresh').click();
    await expect(page.locator('#invites-table tbody')).toContainText('หมดอายุ');
    await page.locator('#invites-table').getByRole('button', { name: 'สร้างคำเชิญใหม่', exact: true }).click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'สร้างคำเชิญใหม่', exact: true }).click();
    await expect(page.locator('#invite-link-box input')).not.toHaveValue(freshLink);
    const acceptLink = await page.locator('#invite-link-box input').inputValue();
    await expect(inviteRow()).toHaveCount(1);
    expect(await page.locator('#invites-table .table-scroll').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await capture('invitations-desktop');

    const guest = await browser.newContext();
    const guestPage = await guest.newPage();
    await guestPage.goto(acceptLink);
    await expect(guestPage.locator('#invite-email-input')).toHaveValue('invite@ui-admin.local');
    await guestPage.locator('#invite-name-input').fill('ทีมงานที่ตอบรับแล้ว');
    await guestPage.locator('#accept-invite-form [name=password]').fill('Chosen@12345');
    await guestPage.locator('#accept-invite-form [name=password_confirm]').fill('Chosen@12345');
    await guestPage.locator('#accept-invite-form [type=submit]').click();
    await expect(guestPage.locator('#view-official')).toBeVisible();
    const denied = await guestPage.evaluate(() => request('users.list', {}, { silent: true }).then(() => false).catch(error => error.message.includes('ไม่มีสิทธิ์')));
    expect(denied).toBe(true);
    await guest.close();
    await page.locator('#admin-users-refresh').click();
    await expect(page.locator('#invites-table tbody')).toContainText('ใช้งานแล้ว');

    await page.locator('#admin-create-invite').click();
    await page.locator('#invite-form [name=email]').fill('revoke@ui-admin.local');
    await page.locator('#invite-role-select').selectOption('public_relations');
    await page.locator('#invite-form [type=submit]').click();
    await expect(page.locator('#invite-form-dialog')).toBeHidden();
    const revokeRow = page.locator('#invites-table tbody tr', { hasText: 'revoke@ui-admin.local' });
    await revokeRow.getByRole('button', { name: 'เพิกถอน', exact: true }).click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'เพิกถอนคำเชิญ', exact: true }).click();
    await expect(revokeRow).toContainText('ถูกเพิกถอน');
    await page.locator('#admin-invite-status-filter').selectOption('revoked');
    await expect(page.locator('#invites-table tbody tr')).toHaveCount(1);
    await page.locator('#admin-invite-status-filter').selectOption('');

    await tab('settings');
    await page.locator('#admin-audit-details > summary').click();
    await expect(page.locator('#audit-full-table tbody')).toContainText('admin@rmutt.local');
    await page.locator('#admin-audit-details > summary').click();
    for (const width of [768, 390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      for (const name of ['members', 'invitations', 'settings']) {
        await tab(name);
        await noOverflow();
        if (width === 390) await capture(name + '-mobile');
      }
      await tab('members');
      await page.getByRole('button', { name: 'เพิ่มสมาชิก', exact: true }).click();
      await expect(page.locator('#user-form-dialog')).toBeVisible();
      expect(await page.locator('#user-form-dialog').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
      if (width === 390) await capture('member-modal-mobile');
      await page.keyboard.press('Escape');
      await expect(page.locator('#user-form-dialog')).toBeHidden();
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#users-table tbody tr', { hasText: 'admin@rmutt.local' }).getByRole('button').click();
    await expect(page.locator('[data-admin-member-action="status"]')).toBeDisabled();
    await expect(page.locator('[data-admin-member-action="delete"]')).toBeDisabled();
    await page.keyboard.press('Escape');
    await memberRow().getByRole('button').click();
    await page.locator('[data-admin-member-action="status"]').click();
    await page.locator('.confirm-dialog').getByRole('button', { name: 'เปิดใช้งานบัญชี', exact: true }).click();
